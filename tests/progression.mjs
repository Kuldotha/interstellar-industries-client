until(()=>c.industry_tutorial()===2,'fish quest completes');assert.equal(c.industry_population(),10);assert.equal(pool()[1],2);
assert.equal(c.industry_unlocked(0),1);assert.equal(c.industry_unlocked(1),1);assert.equal(c.industry_unlocked(4),0);
assert.equal(c.industry_build(quarry,0),0);assert.equal(c.industry_tutorial(),2);assert.equal(c.industry_produced(0),0);
assert.equal(c.industry_build(factory,1),0);assert.equal(c.industry_tutorial(),3);assert.equal(pool()[1],2);assert.equal(c.industry_produced(1),0);
assert.equal(c.industry_workers(),10);for(const kind of [0,1,3])assert.equal(c.industry_productivity(kind),50);
for(let i=0;i<10;i++)c.industry_refresh();assert.equal(pool()[1],2);
for(const h of homes.slice(2))assert.equal(c.industry_build(h,2),0);assert.equal(pool()[1],0);
until(()=>c.industry_population()===20,'four fed houses grow to twenty');assert.equal(c.industry_tutorial(),4);assert.equal(c.industry_unlocked(4),1);assert.equal(pool()[1],3);
for(let i=0;i<10;i++)c.industry_refresh();assert.equal(pool()[1],3);
assert.equal(c.industry_build_cost(4),3);assert.equal(c.industry_build(commons,4),0);
until(()=>c.industry_tutorial()===5,'Commons quest completes');until(()=>c.industry_population()===40,'full capacity is ten per house');
for(const h of homes)c.industry_remove(h);assert.equal(c.industry_population(),0);
for(const kind of [0,1,3,4])assert.equal(c.industry_unlocked(kind),1);
const peak=c.industry_peak_population(),stage=c.industry_tutorial(),produced=[0,1,2].map(r=>c.industry_produced(r));
c.industry_reset();c.industry_restore_progression(peak,stage,...produced);c.industry_refresh();
assert.equal(c.industry_population(),0);for(const kind of [0,1,3,4])assert.equal(c.industry_unlocked(kind),1);assert.equal(pool()[1],2);
c.industry_reset();c.industry_restore_progression(0,6,0,0,0);assert.equal(c.industry_unlocked(3),0);
console.log('Tutorial: immediate chain completion, full workforce efficiency, expansion/Commons rewards exactly once, persistent unlocks and completion pass.');

