import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {questDetails} from '../public/quests.js';
const {instance:{exports:c}}=await WebAssembly.instantiate(readFileSync(new URL('../public/planet_geometry.wasm',import.meta.url)),{});
c.generate_blue(8,.02,23);
const n=c.tile_count(),surfaces=new Uint32Array(c.memory.buffer,c.surfaces_ptr(),n).slice(),features=new Uint32Array(c.memory.buffer,c.features_ptr(),n).slice(),neighbors=new Uint32Array(c.memory.buffer,c.tile_neighbors_ptr(),n*6).slice();
const dry=Array.from(surfaces.keys()).filter(i=>surfaces[i]);
const adjacent=i=>Array.from(neighbors.slice(i*6,i*6+6)).filter(j=>j<n&&surfaces[j]);
const commons=dry.find(i=>adjacent(i).length>=4),homes=adjacent(commons).slice(0,4);
const dock=dry.find(i=>i!==commons&&!homes.includes(i)&&c.industry_valid_sides(i,3));
const quarry=dry.find(i=>i!==commons&&i!==dock&&!homes.includes(i)&&(features[i]&2));
const factory=dry.find(i=>![commons,dock,quarry,...homes].includes(i));
const pool=()=>Array.from(new Uint32Array(c.memory.buffer,c.industry_pool_ptr(),3));
const until=(predicate,label)=>{for(let i=0;i<3600&&!predicate();i++)c.industry_advance(1);assert(predicate(),label);};
assert.equal(pool()[1],2);assert.equal(c.industry_unlocked(2),1);assert.equal(c.industry_unlocked(3),0);
assert.equal(c.industry_build(homes[0],2),0);assert.equal(pool()[1],1);
assert.equal(c.industry_build(homes[1],2),0);assert.equal(pool()[1],1);assert.equal(c.industry_tutorial(),1);assert.equal(c.industry_unlocked(3),1);
for(let i=0;i<10;i++)c.industry_refresh();assert.equal(pool()[1],1);
